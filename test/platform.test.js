import { test } from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { createPlatform } from '../src/server.js';

test('registration, approval, catalog and tenant-isolated order flow', async t => {
  const app = await createPlatform();
  await app.provisionAdmin('admin@example.test', 'admin-test-password');
  const servers = {};
  for (const role of ['admin','cafe','customer']) {
    const server = http.createServer(app.handler(role));
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve)); servers[role] = server;
  }
  t.after(async () => { await Promise.all(Object.values(servers).map(s => new Promise(r => s.close(r)))); await app.close(); });
  async function call(role, path, body, cookie) {
    const res = await fetch(`http://127.0.0.1:${servers[role].address().port}/api/${path}`, { method: body === undefined ? 'GET':'POST', headers: {'Content-Type':'application/json', ...(cookie ? {Cookie:cookie}: {})}, ...(body===undefined?{}:{body:JSON.stringify(body)}) });
    return { status:res.status, cookie:res.headers.get('set-cookie')?.split(';')[0], data:await res.json() };
  }
  const register = (role,email,extra={}) => call(role,'register',{email,password:'test-password-123',...extra});
  assert.equal((await register('admin','bad@example.test')).status,403);
  assert.equal((await register('cafe','one@example.test',{name:'Kisumu Cyber',location:'Kisumu'})).status,201);
  await register('cafe','two@example.test',{name:'Nairobi Cyber',location:'Nairobi'});
  await register('customer','customer@example.test');
  const login = async (role,email,password='test-password-123') => (await call(role,'login',{email,password})).cookie;
  const owner = await login('cafe','one@example.test');
  const other = await login('cafe','two@example.test');
  const customer = await login('customer','customer@example.test');
  const admin = await login('admin','admin@example.test','admin-test-password');
  assert.equal((await call('admin','dashboard',undefined,owner)).status,401);
  assert.equal((await call('admin','dashboard',undefined,customer.replace('izi_customer','izi_admin'))).status,401);
  assert.equal((await call('cafe','services',{name:'CV formatting',price:500},owner)).status,403);
  assert.equal((await call('customer','catalog')).data.cafes.length,0);
  assert.equal((await call('admin','cafes/review',{id:1,status:'approved'},admin)).status,200);
  assert.equal((await call('cafe','services',{name:'CV formatting',price:500},owner)).status,201);
  assert.equal((await call('cafe','services',{name:'Bad price',price:-20},owner)).status,400);
  const catalog = (await call('customer','catalog')).data;
  assert.equal(catalog.cafes.length,1);
  assert.equal((await call('customer','orders',{service_id:1,instructions:'Format my CV',price:1,cafe_id:2},customer)).status,201);
  const order = (await call('cafe','dashboard',undefined,owner)).data.orders[0];
  assert.equal(order.price,500); assert.equal(order.cafe_id,1); assert.equal(order.status,'requested');
  assert.equal((await call('cafe','dashboard',undefined,other)).data.orders.length,0);
  await register('customer','other@example.test');
  const otherCustomer = await login('customer','other@example.test');
  assert.equal((await call('customer','dashboard',undefined,otherCustomer)).data.orders.length,0);
  assert.equal((await call('customer','cafes/review',{id:1,status:'approved'},customer)).status,404);
  await t.test('private documents and conversations', async () => {
    const encoded=Buffer.from('%PDF-1.7\nexample document').toString('base64');
    assert.equal((await call('customer','orders/1/files',{name:'cv.pdf',content:encoded},customer)).status,201);
    assert.equal((await call('customer','orders/1/files',{name:'fake.pdf',content:Buffer.from('not a PDF').toString('base64')},customer)).status,400);
    assert.equal((await call('customer','orders/1/files',{name:'../cv.pdf',content:encoded},customer)).status,400);
    assert.equal((await call('customer','orders/1/files',{name:'cv.pdf',content:'not base64'},customer)).status,400);
    assert.equal((await call('customer','orders/1/files',{name:'cv.txt',content:Buffer.alloc(5*1024*1024+1,65).toString('base64')},customer)).status,413);
    assert.equal((await call('customer','orders/1/messages',{message:'Please keep this to two pages.'},customer)).status,201);
    assert.equal((await call('cafe','orders/1/messages',{message:'I can do that.'},owner)).status,201);
    assert.equal((await call('cafe','orders/1',undefined,owner)).data.messages.length,2);
    assert.equal((await call('cafe','orders/1',undefined,other)).status,404);
    assert.equal((await call('customer','orders/1',undefined,otherCustomer)).status,404);
    assert.equal((await call('admin','orders/1',undefined,admin)).status,404);
    assert.equal((await call('customer','orders/1/files/1',undefined,otherCustomer)).status,404);
    assert.equal((await call('cafe','orders/1/files/1',undefined,other)).status,404);
    const download=await fetch(`http://127.0.0.1:${servers.cafe.address().port}/api/orders/1/files/1`,{headers:{Cookie:owner}});
    assert.equal(download.status,200);
    assert.equal(download.headers.get('cache-control'),'no-store');
    assert.match(download.headers.get('content-disposition'),/^attachment/);
    assert.equal(await download.text(),Buffer.from(encoded,'base64').toString());
  });
  await t.test('versioned quote acceptance and payment gate', async () => {
    const quote={amount:800,scope:'Format two pages, one revision included',turnaround:'One day after payment'};
    assert.equal((await call('cafe','orders/1/quotes',quote,other)).status,404);
    const first=await call('cafe','orders/1/quotes',quote,owner);
    assert.equal(first.status,201);
    const second=await call('cafe','orders/1/quotes',{...quote,amount:700},owner);
    assert.equal((await call('customer','orders/1/accept-quote',{quote_id:first.data.id},customer)).status,409);
    assert.equal((await call('customer','orders/1/accept-quote',{quote_id:second.data.id,amount:1},customer)).status,200);
    const detail=(await call('customer','orders/1',undefined,customer)).data;
    assert.equal(detail.order.price,700);
    assert.equal(detail.order.status,'awaiting_payment');
    assert.equal(detail.quotes[0].status,'accepted');
    assert.equal(detail.quotes[1].status,'superseded');
    assert.equal((await call('customer','orders/1/accept-quote',{quote_id:second.data.id},customer)).status,409);
    assert.equal((await call('cafe','orders/1/quotes',quote,owner)).status,409);
    assert.equal((await call('cafe','orders/1/complete',{},owner)).status,404);
  });
  await call('admin','cafes/review',{id:1,status:'suspended'},admin);
  assert.equal((await call('cafe','orders/1/files/1',undefined,owner)).status,403);
  assert.equal((await call('customer','orders/1/messages',{message:'test'},customer)).status,403);
  assert.equal((await call('customer','orders',{service_id:1,instructions:'Another job'},customer)).status,404);
  await call('customer','logout',{},customer);
  assert.equal((await call('customer','dashboard',undefined,customer)).status,401);
});
